"""Safe, service-backed PDF export with individually recorded outcomes.

Filesystem publication and the SQLite status update cannot be one transaction.
On failure we *try* to restore the previous file, never delete a backup that
was not restored, and report both the primary error and recovery/cleanup issues.
"""
from __future__ import annotations

import errno
import os
import re
import shutil
import tempfile
from dataclasses import dataclass, field
from datetime import date
from pathlib import Path
from typing import Callable, Mapping

from app.core.service import CalculationService

from .act import render_act
from .invoice import render_invoice

_RENDERERS = {"act": render_act, "invoice": render_invoice}
_INVALID_WINDOWS = re.compile(r'[<>:"/\\|?*\x00-\x1f]')
_RESERVED_WINDOWS = {"CON", "PRN", "AUX", "NUL", *(f"COM{i}" for i in range(1, 10)),
                     *(f"LPT{i}" for i in range(1, 10))}
_LINK_UNSUPPORTED = {errno.ENOTSUP, errno.EOPNOTSUPP, errno.ENOSYS, errno.EPERM,
                     errno.EINVAL}


class ExportError(RuntimeError):
    """Export failed; the document was not marked generated by this invocation.

    ``backup_path`` is retained when rollback fails; ``path`` identifies any
    file that may need manual recovery. The original error is ``__cause__``.
    """

    def __init__(self, message: str, *, path: Path | None = None,
                 recovery_failed: bool = False, backup_path: Path | None = None,
                 recovery_error: BaseException | None = None,
                 cleanup_error: BaseException | None = None,
                 staged_path: Path | None = None,
                 partial_path: Path | None = None,
                 quarantine_path: Path | None = None,
                 cleanup_errors: tuple[BaseException, ...] = ()) -> None:
        super().__init__(message)
        self.path = path
        self.recovery_failed = recovery_failed
        self.backup_path = backup_path
        self.staged_path = staged_path
        self.partial_path = partial_path
        self.quarantine_path = quarantine_path
        self.recovery_error = recovery_error
        self.cleanup_error = cleanup_error
        self.cleanup_errors = cleanup_errors or ((cleanup_error,) if cleanup_error is not None else ())


class ExportCancelled(ExportError):
    """Cancellation before reserving document metadata or changing a file."""


@dataclass(frozen=True)
class ExportedDocument:
    kind: str
    path: Path
    document_id: int
    number: int
    document_date: str
    # A successfully published document stays successful if backup cleanup fails.
    cleanup_warning: str | None = None
    leftover_backup: Path | None = None
    leftover_staged: Path | None = None


@dataclass
class ExportBatchResult:
    successful: dict[str, ExportedDocument] = field(default_factory=dict)
    failed: dict[str, Exception] = field(default_factory=dict)


def safe_filename(kind: str, number: int, tenant_name: str, year: int, month: int) -> str:
    """Portable PDF filename for UI defaults and future ZIP export."""
    if kind not in _RENDERERS:
        raise ValueError("Неизвестный вид документа.")
    cleaned = _INVALID_WINDOWS.sub("_", str(tenant_name))
    cleaned = re.sub(r"\s+", " ", cleaned).strip(" .")[:75].rstrip(" .") or "Арендатор"
    if cleaned.split(".")[0].upper() in _RESERVED_WINDOWS:
        cleaned = "_" + cleaned
    label = "Акт" if kind == "act" else "Счет"
    return f"{label}_{number}_{cleaned}_{month:02d}-{year:04d}.pdf"


def _validate_target(path: Path, overwrite: bool) -> None:
    if path.suffix.lower() != ".pdf" or not path.name or _INVALID_WINDOWS.search(path.name):
        raise ValueError("Имя файла должно быть допустимым и иметь расширение .pdf.")
    if path.stem.split(".")[0].upper() in _RESERVED_WINDOWS or path.name.endswith((" ", ".")):
        raise ValueError("Недопустимое имя файла Windows.")
    if not path.parent.is_dir():
        raise FileNotFoundError("Каталог для PDF не существует.")
    # Avoid following or overwriting target-file symlinks, including dangling ones.
    # A symlinked parent is allowed, but must be resolved for batch alias checks.
    if path.is_symlink():
        raise ValueError("Путь к PDF не должен быть символической ссылкой на файл.")
    if path.is_dir():
        raise IsADirectoryError(str(path))
    if not overwrite and path.exists():
        raise FileExistsError(f"Файл уже существует: {path}")


def _case_sensitive_directory(parent: Path) -> bool:
    """Probe the actual directory, not os.path.normcase() or platform alone.

    NTFS directories can opt into case sensitivity; POSIX filesystems may be
    case-insensitive. Only invoked when filenames differ just by case.
    """
    fd, name = tempfile.mkstemp(prefix=".kontakt-CaseProbe-", suffix="-Aa", dir=parent)
    os.close(fd)
    sample = Path(name)
    try:
        variant = sample.with_name(sample.name[:-2] + "aA")
        return not variant.exists() or not os.path.samefile(sample, variant)
    finally:
        sample.unlink()


def _same_destination(left: Path, right: Path) -> bool:
    # samefile covers existing hard links and symlinks to the same inode.
    if left.exists() and right.exists() and os.path.samefile(left, right):
        return True
    a, b = left.resolve(strict=False), right.resolve(strict=False)
    if str(a) == str(b):
        return True
    # For non-existent targets or aliases to their directories, compare the
    # physical parent and then the prospective basenames.
    if not a.parent.is_dir() or not b.parent.is_dir():
        return False
    if not os.path.samefile(a.parent, b.parent):
        return False
    if a.name == b.name:
        return True
    if a.name.casefold() == b.name.casefold():
        return not _case_sensitive_directory(a.parent)
    return False


def _assert_unique_destinations(paths: Mapping[str, Path]) -> None:
    entries = list(paths.items())
    for i, (_, path) in enumerate(entries):
        for _, other in entries[i + 1:]:
            if _same_destination(path, other):
                raise ValueError("Акт и счёт ссылаются на один физический целевой файл.")



def _stage_pdf(path: Path, data: bytes) -> Path:
    fd, name = tempfile.mkstemp(prefix=".kontakt-pdf-", suffix=".tmp", dir=path.parent)
    staged = Path(name)
    open_fd: int | None = fd
    identity: tuple[int, int] | None = None
    try:
        info = os.fstat(fd)
        identity = info.st_dev, info.st_ino
        output = os.fdopen(fd, "wb")
        open_fd = None
        with output as out:
            out.write(data)
            out.flush()
            os.fsync(out.fileno())
        return staged
    except BaseException as original:
        if open_fd is not None:
            os.close(open_fd)
        try:
            if identity is None:
                raise OSError("Идентификатор staged PDF неизвестен; удаление запрещено.")
            _unlink_if_owned(staged, identity)
        except BaseException as cleanup:
            raise ExportError(
                "Не удалось удалить неполный временный PDF после ошибки записи.",
                staged_path=staged, cleanup_error=cleanup,
            ) from original
        raise


def _backup(path: Path) -> Path:
    fd, name = tempfile.mkstemp(prefix=".kontakt-backup-", suffix=".pdf", dir=path.parent)
    backup = Path(name)
    open_fd: int | None = fd
    identity: tuple[int, int] | None = None
    try:
        info = os.fstat(fd)
        identity = info.st_dev, info.st_ino
        output = os.fdopen(fd, "wb")
        open_fd = None
        # mkstemp uses private permissions; do not copy source mode.
        with output as out, path.open("rb") as source:
            shutil.copyfileobj(source, out)
            out.flush()
            os.fsync(out.fileno())
        return backup
    except BaseException as original:
        if open_fd is not None:
            os.close(open_fd)
        try:
            if identity is None:
                raise OSError("Идентификатор backup PDF неизвестен; удаление запрещено.")
            _unlink_if_owned(backup, identity)
        except BaseException as cleanup:
            raise ExportError(
                "Не удалось удалить неполную резервную копию после ошибки записи.",
                backup_path=backup, cleanup_error=cleanup,
            ) from original
        raise


def _identity(path: Path) -> tuple[int, int, int, int]:
    """Include size/mtime to detect inode reuse and in-place foreign writes.

    Do not use ctime: creating a hard link legitimately updates inode ctime.
    Even this is best-effort; a hostile process can modify metadata deliberately.
    """
    stat = path.stat(follow_symlinks=False)
    return stat.st_dev, stat.st_ino, stat.st_size, stat.st_mtime_ns


def _unlink_if_owned(path: Path, identity: tuple[int, ...]) -> None:
    """Do not unlink a replaced file; pre-write fd snapshots only know dev/inode."""
    if _identity(path)[:len(identity)] != identity:
        raise OSError("Целевой файл изменён сторонним процессом; удаление запрещено.")
    path.unlink()


def _publish_new_file(staged: Path, target: Path) -> None:
    """No-clobber publication, with a portable exclusive-create fallback.

    Hard links publish a complete file immediately; FAT/exFAT and some other
    filesystems cannot create them. On those filesystems, O_EXCL prevents a
    race with another creator. A partially written file is removed on error.
    """
    try:
        os.link(staged, target)
        return
    except OSError as exc:
        if exc.errno not in _LINK_UNSUPPORTED and getattr(exc, "winerror", None) not in (1, 50, 1314):
            raise

    # O_EXCL is essential: never open the target in truncating 'wb' mode.
    flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, "O_BINARY", 0)
    fd = os.open(target, flags, 0o600)
    open_fd: int | None = fd
    identity: tuple[int, int] | None = None
    try:
        info = os.fstat(fd)
        identity = info.st_dev, info.st_ino
        output = os.fdopen(fd, "wb")
        open_fd = None
        with output as out, staged.open("rb") as source:
            shutil.copyfileobj(source, out, length=1024 * 1024)
            out.flush()
            os.fsync(out.fileno())
    except BaseException as original:
        if open_fd is not None:
            os.close(open_fd)
        try:
            if identity is None:
                raise OSError("Идентификатор частичного PDF неизвестен; удаление запрещено.")
            _unlink_if_owned(target, identity)
        except BaseException as cleanup:
            raise ExportError(
                "Запись PDF прервана; неполный файл не удалось удалить.",
                path=target, partial_path=target, recovery_failed=True,
                cleanup_error=cleanup
            ) from original
        raise


class _UnsafeRollback(OSError):
    """Rollback could not safely complete; a quarantined file may need recovery."""

    def __init__(self, message: str, quarantined_path: Path | None = None) -> None:
        super().__init__(message)
        self.quarantined_path = quarantined_path


def _rollback_published(target: Path, backup: Path | None,
                        published_identity: tuple[int, ...] | None
                        ) -> tuple[Path | None, BaseException | None]:
    """Restore without replacing a foreign file in a check/replace race.

    First move the current target to a private quarantine, then verify *what
    was actually moved*. Restore the backup through no-clobber publication.
    If another process wins the race, leave backup/quarantine for manual
    recovery instead of overwriting that process's PDF.
    """
    if published_identity is None:
        raise _UnsafeRollback("Идентификатор опубликованного PDF неизвестен; откат запрещён.")
    if _identity(target) != published_identity:
        raise _UnsafeRollback("Целевой PDF заменён другим процессом; откат запрещён.")

    fd, name = tempfile.mkstemp(prefix=".kontakt-rollback-", suffix=".pdf", dir=target.parent)
    try:
        placeholder = os.fstat(fd)
    finally:
        os.close(fd)
    quarantine = Path(name)
    moved = False
    try:
        os.replace(target, quarantine)
        moved = True
        moved_identity = _identity(quarantine)
        if moved_identity != published_identity:
            # The other process changed the file *after* our first check.
            # Return its exact contents without clobbering a new target.
            try:
                _publish_new_file(quarantine, target)
                _unlink_if_owned(quarantine, moved_identity)
            except BaseException as exc:
                raise _UnsafeRollback(
                    "Чужой PDF перемещён в карантин; требуется ручное восстановление.",
                    quarantine,
                ) from exc
            raise _UnsafeRollback(
                "Во время отката был обнаружен чужой PDF; он восстановлен без перезаписи."
            )

        if backup is not None:
            # Unlike os.replace(backup, target), this cannot clobber a file
            # created by another process after target was moved.
            _publish_new_file(backup, target)
        try:
            _unlink_if_owned(quarantine, published_identity)
        except BaseException as cleanup:
            # The previous PDF is restored (or the new one removed); leaving
            # a private copy of the published PDF is only a cleanup problem.
            return quarantine, cleanup
        return None, None
    except BaseException as exc:
        if moved:
            if isinstance(exc, _UnsafeRollback):
                raise
            raise _UnsafeRollback(
                "Безопасный откат не завершён; временный PDF сохранён.",
                quarantine,
            ) from exc
        try:
            _unlink_if_owned(quarantine, (placeholder.st_dev, placeholder.st_ino))
        except OSError as cleanup:
            raise _UnsafeRollback(
                "Не удалось удалить временный файл неудачного отката.",
                quarantine,
            ) from exc
        raise


def export_document(service: CalculationService, calculation_id: int, kind: str,
                    path: str | Path, *, overwrite: bool = False,
                    document_date: date | str | None = None, number: int | None = None,
                    confirm_duplicate: bool = False, confirm_zero: bool = False,
                    cancelled: bool = False,
                    _pre_publish: Callable[[], None] | None = None) -> ExportedDocument:
    """Export one document, preserving the previous PDF if a later step fails.

    All cleanup problems are available in the structured result/error. A
    successful SQLite update is never undone because a backup cannot be deleted.
    """
    if cancelled:
        raise ExportCancelled("Экспорт отменён до создания документа.")
    if kind not in _RENDERERS:
        raise ValueError("Неизвестный вид документа.")
    target = Path(path).expanduser().absolute()
    _validate_target(target, overwrite)
    document = service.reserve_document(
        calculation_id, kind, document_date=document_date, number=number,
        confirm_duplicate=confirm_duplicate, confirm_zero=confirm_zero)
    snapshot = service.prepare_document(calculation_id, kind, confirm_zero=confirm_zero)
    if snapshot["document"]["id"] != document["id"]:
        raise ExportError("Метаданные документа изменились до генерации.")
    pdf_bytes = _RENDERERS[kind](snapshot)
    if not pdf_bytes.startswith(b"%PDF-"):
        raise ExportError("Генератор не вернул корректный заголовок PDF.")
    latest = service.prepare_document(calculation_id, kind, confirm_zero=confirm_zero)
    if latest["revision"] != snapshot["revision"]:
        raise ExportError("Данные изменились во время подготовки PDF; файл не записан.")

    staged: Path | None = None
    staged_identity: tuple[int, int] | None = None
    leftover_staged: Path | None = None
    backup: Path | None = None
    backup_identity: tuple[int, int] | None = None
    published_identity: tuple[int, ...] | None = None
    quarantine_path: Path | None = None
    saved = False
    marked = False
    error: BaseException | None = None
    recovery_error: BaseException | None = None
    cleanup_errors: list[BaseException] = []
    try:
        staged = _stage_pdf(target, pdf_bytes)
        staged_identity = _identity(staged)
        _validate_target(target, overwrite)
        if _pre_publish is not None:
            _pre_publish()  # Re-evaluate aliases just before file publication.
        if overwrite:
            if target.exists():
                backup = _backup(target)
                backup_identity = _identity(backup)
            os.replace(staged, target)
            staged = None
        else:
            _publish_new_file(staged, target)
        saved = True
        # If stat fails here, ownership is UNKNOWN: never restore by replacing
        # the target, even if the previous file has a valid backup.
        published_identity = _identity(target)
        service.mark_document_generated(document["id"], expected_revision=snapshot["revision"])
        marked = True
    except BaseException as exc:
        error = exc
        if saved:
            try:
                quarantine_path, quarantine_cleanup = _rollback_published(
                    target, backup, published_identity)
                if quarantine_cleanup is not None:
                    cleanup_errors.append(quarantine_cleanup)
            except BaseException as rollback_exc:
                recovery_error = rollback_exc
                quarantine_path = getattr(rollback_exc, "quarantined_path", None)
    finally:
        if staged is not None:
            try:
                if staged_identity is None:
                    raise OSError("Идентификатор staged PDF неизвестен; удаление запрещено.")
                _unlink_if_owned(staged, staged_identity)
            except BaseException as cleanup:
                cleanup_errors.append(cleanup)
                leftover_staged = staged

    if error is not None:
        # A backup is never deleted when recovery has failed. On successful
        # recovery or a pre-publication failure it is normally no longer needed.
        if backup is not None and recovery_error is None:
            try:
                if backup_identity is None:
                    raise OSError("Идентификатор backup PDF неизвестен; удаление запрещено.")
                _unlink_if_owned(backup, backup_identity)
            except BaseException as cleanup:
                cleanup_errors.append(cleanup)
            else:
                backup = None
        previous = error if isinstance(error, ExportError) else None
        additional = list(previous.cleanup_errors) if previous is not None else []
        additional.extend(cleanup_errors)
        if isinstance(error, (KeyboardInterrupt, SystemExit)) and not recovery_error and not additional:
            raise error
        if isinstance(error, ExportError) and not saved and not additional:
            raise error

        message = "Не удалось завершить экспорт PDF; отметка генерации не установлена."
        if recovery_error is not None:
            message += " Безопасное восстановление не завершено; проверьте сохранённые файлы."
            if backup is not None:
                message += " Резервная копия сохранена для ручного восстановления."
        if additional:
            message += " Остались файлы, требующие ручной очистки."
        backup_path = backup if backup is not None else (previous.backup_path if previous else None)
        partial_path = previous.partial_path if previous else None
        staged_path = leftover_staged or (previous.staged_path if previous else None)
        quarantine = quarantine_path or (previous.quarantine_path if previous else None)
        primary_cause = (error.__cause__ if previous is not None and error.__cause__ is not None
                         else error)
        raise ExportError(
            message,
            path=target if recovery_error is not None else (previous.path if previous else None),
            recovery_failed=recovery_error is not None or (previous.recovery_failed if previous else False),
            backup_path=backup_path,
            staged_path=staged_path,
            partial_path=partial_path,
            quarantine_path=quarantine,
            recovery_error=recovery_error or (previous.recovery_error if previous else None),
            cleanup_error=additional[0] if additional else None,
            cleanup_errors=tuple(additional),
        ) from primary_cause

    # The database already records a successful export. Cleanup cannot undo it.
    warnings = []
    leftover_backup = None
    if backup is not None:
        try:
            if backup_identity is None:
                raise OSError("Идентификатор backup PDF неизвестен; удаление запрещено.")
            _unlink_if_owned(backup, backup_identity)
        except BaseException as cleanup:
            leftover_backup = backup
            cleanup_errors.append(cleanup)
            warnings.append("Не удалось удалить конфиденциальную резервную копию PDF; удалите её вручную.")
    if leftover_staged is not None:
        warnings.append("Не удалось удалить конфиденциальный staged PDF; удалите его вручную.")
    assert marked
    return ExportedDocument(
        kind, target, document["id"], document["number"],
        document["document_date"], " ".join(warnings) or None,
        leftover_backup, leftover_staged,
    )


def export_documents(service: CalculationService, calculation_id: int,
                     paths: Mapping[str, str | Path], *, overwrite: bool = False,
                     confirm_zero: bool = False, confirm_duplicate: bool = False,
                     cancelled: bool = False) -> ExportBatchResult:
    """Preflight path aliases before publishing either document.

    Individual export failures remain isolated; we also re-check the pair
    immediately before each publication to limit filesystem TOCTOU windows.
    """
    result = ExportBatchResult()
    normalized = {kind: Path(path).expanduser().absolute() for kind, path in paths.items()}
    _assert_unique_destinations(normalized)
    for kind, path in normalized.items():
        try:
            result.successful[kind] = export_document(
                service, calculation_id, kind, path, overwrite=overwrite,
                confirm_zero=confirm_zero, confirm_duplicate=confirm_duplicate,
                cancelled=cancelled,
                _pre_publish=lambda: _assert_unique_destinations(normalized))
        except Exception as exc:
            result.failed[kind] = exc
    return result
