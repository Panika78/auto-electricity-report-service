"""Authorization of disposable synthetic QA profiles (not an adversarial sandbox)."""
from __future__ import annotations

import ctypes
import json
import os
import re
import secrets
import sys
from pathlib import Path

from app.data import database as db

MARKER_NAME = ".kontakt-qa-profile.json"
_PURPOSE = "kontakt-synthetic-release-qa"


def _same(left: Path, right: Path) -> bool:
    return os.path.normcase(str(left.resolve())) == os.path.normcase(str(right.resolve()))


def _system_profile_paths() -> tuple[Path, ...]:
    """Consult Windows Shell independently of overrideable LOCALAPPDATA."""
    if sys.platform == "win32":
        folders = []
        # CSIDL_PROFILE, CSIDL_LOCAL_APPDATA, CSIDL_APPDATA.
        for folder in (0x28, 0x1C, 0x1A):
            buffer = ctypes.create_unicode_buffer(1024)
            if ctypes.windll.shell32.SHGetFolderPathW(None, folder, None, 0, buffer) != 0 or not buffer.value:
                raise RuntimeError("Не удалось определить настоящий системный профиль Windows.")
            folders.append(Path(buffer.value).resolve())
        return tuple(folders)
    return (Path.home().resolve(), (Path.home() / ".local" / "share").resolve())


def _check_root(root: Path) -> None:
    if not root.is_absolute() or not root.is_dir() or root.is_symlink():
        raise RuntimeError("Нужен существующий отдельный каталог QA-профиля.")
    for system in _system_profile_paths():
        if _same(root, system) or _same(root, system / "ElectricityReports"):
            raise RuntimeError("QA запрещён в реальном системном профиле пользователя.")


def create_qa_profile(root: Path) -> str:
    """Create a one-time marker, refusing profiles with pre-existing data."""
    root = Path(root)
    _check_root(root)
    root = root.resolve()
    if (root / "ElectricityReports").exists():
        raise RuntimeError("Тестовый профиль уже содержит каталог базы данных.")
    token = secrets.token_hex(32)
    with (root / MARKER_NAME).open("x", encoding="utf-8") as file:
        json.dump({"format_version": 1, "purpose": _PURPOSE,
                   "root": str(root), "token": token}, file)
    return token


def validate_qa_profile() -> Path:
    """Fail before Qt settings or SQLite can access an unintended profile."""
    selected = os.environ.get("KONTAKT_SMOKE_ROOT")
    token = os.environ.get("KONTAKT_SMOKE_TOKEN", "")
    if not selected or not re.fullmatch(r"[a-f0-9]{64}", token):
        raise RuntimeError("Не задан токен/маркер тестового профиля.")
    raw = Path(selected).expanduser()
    if not raw.is_absolute():
        raise RuntimeError("Каталог тестового профиля должен иметь абсолютный путь.")
    _check_root(raw)
    root = raw.resolve()
    marker = root / MARKER_NAME
    if marker.is_symlink() or not marker.is_file():
        raise RuntimeError("Не найден маркер тестового профиля.")
    try:
        data = json.loads(marker.read_text(encoding="utf-8"))
    except (OSError, UnicodeError, ValueError) as error:
        raise RuntimeError("Некорректный маркер тестового профиля.") from error
    if (data.get("format_version") != 1 or data.get("purpose") != _PURPOSE
            or data.get("root") != str(root)
            or not secrets.compare_digest(str(data.get("token", "")), token)):
        raise RuntimeError("Маркер тестового профиля не совпадает с токеном.")
    if not _same(db.get_database_path(), root / "ElectricityReports" / "app.db"):
        raise RuntimeError("Путь базы данных не соответствует тестовому профилю.")
    return root


def validate_qa_result_path(selected: str, root: Path) -> Path:
    """Accept only a new synthetic probe result directly inside the QA profile.

    A fresh, unguessable filename is generated by the harness for *each* run.
    Exclusive creation at write time is still required against file races.
    """
    path = Path(selected).expanduser()
    if not path.is_absolute():
        raise RuntimeError("Путь результата QA должен быть абсолютным.")
    if not re.fullmatch(r"qa-result-[a-f0-9]{32}\.txt", path.name):
        raise RuntimeError("Недопустимое имя файла результата QA.")
    if not _same(path.parent, root) or not _same(path, root / path.name):
        raise RuntimeError("Файл результата QA должен находиться внутри тестового профиля.")
    if path.exists() or path.is_symlink():
        raise RuntimeError("Файл результата QA уже существует: перезапись запрещена.")
    return root / path.name
